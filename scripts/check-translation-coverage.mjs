#!/usr/bin/env node
// #718: no page may quietly answer a translated locale in English.
//
// The defect this exists for: three pages under /ja/ served English bodies, and nothing in the
// toolchain had an opinion. Starlight does render a fallback notice, so they were not literally
// silent, but "not translated yet" was the wrong sentence for pages that are generated from code
// and will never have a hand-written mirror. Either way, the toolchain never asked whether a
// fallback was intended.
//
// So this walks the BUILT site and asserts every fallback page is declared here with a reason.
// Discovery from dist, not from a list of known pages: a page added tomorrow without its ja mirror
// is red on the day it lands, which is the failure mode that let 42 pages ship untranslated
// wording in the first place.
//
//   pnpm build   (this runs last in the chain)
import { readdirSync, statSync, readFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { TRANSLATIONS, assertLocalesMatchConfig } from './locales.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const DIST = join(root, 'dist')

// A fallback page is allowed only with a reason, and only where a translation genuinely cannot
// exist. `reference/**` is pulled from the product's code by pull-generated.mjs; a ja
// mirror would be overwritten by the next pull, so English is the honest answer and the notice
// override says exactly that. Anything else belongs in a translation, not in this list.
//
// ⚠️ #748 moved these pages out of a `generated/` folder, so the allowance can no longer be a path
// prefix — `reference/` now also holds hand-written, translated pages, and a prefix rule would quietly
// excuse those from ever being translated. The allowance is DERIVED from the pages themselves: a
// pulled page carries the generator's AUTO-GENERATED banner, and nothing hand-written does. That also
// means a new generated page is covered the day it lands, with nobody remembering to add it.
// ⚠️ Not the generators' own banner: they do not agree on its wording ("AUTO-GENERATED — DO NOT
// EDIT" from three of them, "GENERATED by …" from the two environment ones), and a check that reads
// each generator's prose inherits every future generator's spelling. The mark this reads is the one
// PULL-GENERATED stamps on every page it writes, which is by definition on all of them and on
// nothing else.
const GENERATED_MARK = 'This page is generated from the product'
const CONTENT = join(root, 'src/content/docs')

function generatedSlugs() {
  const out = []
  const walk = (dir, rel) => {
    for (const name of readdirSync(dir)) {
      const p = join(dir, name)
      if (statSync(p).isDirectory()) { walk(p, `${rel}${name}/`); continue }
      if (!name.endsWith('.md')) continue
      if (readFileSync(p, 'utf8').includes(GENERATED_MARK)) out.push(`${rel}${name.replace(/\.md$/, '')}`)
    }
  }
  walk(CONTENT, '')
  return out
}

const ALLOWED = generatedSlugs().map((slug) => ({
  prefix: slug,
  why: 'generated from the product source (pull-generated.mjs); a hand-written ja mirror is overwritten by the next pull',
}))
if (ALLOWED.length === 0) {
  console.error('check-translation-coverage: found no generated pages — the marker walk stopped working, and an empty allowance would fail every pulled page')
  process.exit(1)
}

// The sentence Starlight stamps on a fallback page, per locale, and the one this site's override
// puts on the generated references instead. Matching the visible sentence (rather than a CSS class)
// is deliberate: the sentence is the thing the reader is promised, so the check reads what they read.
const NOTICE = { ja: 'このコンテンツはまだ日本語訳がありません。' }
const OVERRIDE_NOTICE = 'このリファレンスは製品のコードから生成しているため、英語のみです。'

const isFallbackPage = (html, locale) =>
  (NOTICE[locale] !== undefined && html.includes(NOTICE[locale])) || html.includes(OVERRIDE_NOTICE)

if (!existsSync(DIST)) {
  console.error('check-translation-coverage: no dist/ — run `pnpm build` first.')
  process.exit(1)
}

// The same reconciliation every other guard does (#713): a locale the site serves but this list
// does not know about would be scanned by nothing.
assertLocalesMatchConfig()

function pagesUnder(base) {
  const out = []
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name)
      if (e.isDirectory()) walk(p)
      // dist/<locale>/index.html is the locale home; dist/<locale>/guides/pages/index.html is a page.
      else if (e.name === 'index.html') out.push({ rel: p.slice(base.length + 1).replace(/(^|\/)index\.html$/, ''), file: p })
    }
  }
  walk(base)
  return out
}

const problems = []
let scanned = 0
let fallbacksSeen = 0

for (const locale of TRANSLATIONS) {
  const dir = join(DIST, locale)
  if (!existsSync(dir)) {
    problems.push(`locale "${locale}" is configured but built no pages (dist/${locale} does not exist)`)
    continue
  }
  if (NOTICE[locale] === undefined) {
    problems.push(`locale "${locale}" has no fallback-notice sentence here, so its pages cannot be inspected — add it to NOTICE`)
    continue
  }
  const pages = pagesUnder(dir)
  scanned += pages.length
  // A locale that builds almost nothing means the walk found the wrong tree, not that the site is
  // small. 20 is far below the real count (48) and far above an accident.
  if (pages.length < 20) {
    problems.push(`locale "${locale}" built only ${pages.length} pages — refusing a vacuously green run`)
  }
  for (const { rel, file } of pages) {
    if (!isFallbackPage(readFileSync(file, 'utf8'), locale)) continue
    fallbacksSeen++
    if (!ALLOWED.some((a) => rel.startsWith(a.prefix))) {
      problems.push(
        `/${locale}/${rel} answers in English (fallback content). Translate it, or declare it in ALLOWED with the reason it cannot be.`
      )
    }
  }
}

// The detector has to be able to fail. With no fallback anywhere, nothing here proves the sentence
// is still the one Starlight renders — the same shape as a pin that passes because it matched
// nothing. If every page really does get translated, delete ALLOWED and this branch together.
if (fallbacksSeen === 0) {
  problems.push(
    'no fallback page found in any locale — either every page is now translated (then remove ALLOWED and this check together), or the notice wording changed and this check is looking for a sentence that no longer exists'
  )
}

if (problems.length > 0) {
  console.error('check-translation-coverage FAILED:')
  for (const p of problems) console.error(`  - ${p}`)
  process.exit(1)
}

console.log(
  `check-translation-coverage OK — ${scanned} translated pages scanned, ${fallbacksSeen} declared English-only ` +
    `(${ALLOWED.map((a) => a.prefix).join(', ')})`
)
