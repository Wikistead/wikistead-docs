#!/usr/bin/env node
// #731: the documentation calls each admin tab what the product calls it.
//
// The defect: the docs had "Sign-in methods" for a tab the product labels Authentication, and two
// more tabs under names their Japanese labels never use. Somebody following the guide looked for a
// tab that is not on the screen. Nothing could notice, because the two vocabularies live in
// different repositories — the ledger binds a PAGE to each tab id, but never compared the words.
//
// So this compares them, against the product's own strings rather than a list written here. The
// labels arrive as `admin-tabs.json`, generated by the source repo from `adminNav` and carried over
// by pull-generated. That indirection is the point (#731): #732 renamed several of these
// labels on the very day this landed, and a check with the words baked in would have gone red for
// being correct. This one follows the product wherever it goes — including to a tab that does not
// exist yet, because an id with no page named after it is also reported.
//
//   pnpm check:admin-tab-names     (runs inside `pnpm build`)
import { readFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { TRANSLATIONS, ROOT_LOCALE } from './locales.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const TABLE = join(root, 'src/content/generated/admin-tabs.json')

// Which page documents which tab id.
//
// WHAT THIS CHECKS, exactly: the page names its tab THE WAY THE PRODUCT DOES — either the title IS
// the label, or the page introduces it as `Admin → <label>` (or the localized form in `introduced` below), which is how every
// one of these pages opens. That is the defect it was written for: a page presenting the tab under a
// name the product does not use, so a reader looks for something that is not on the screen.
//
// ⚠️ The first version of this check only asked whether the label appeared ANYWHERE on the page, and
// it was vacuously green: the Authentication tab's short label sits inside the two-factor label as
// a substring, so a page retitled back to the wrong name still passed. A short label inside a longer
// word is not a mention of the tab. The
// break-check below is what caught it — a pin that cannot be made to fail is not a pin.
//
// WHAT IT DOES NOT CHECK: that the title equals the label. Several pages are deliberately longer
// than their tab ("Members & invites" for the Members tab, "Spaces (admin)" to separate it from the
// spaces guide), which is why the `Admin → <label>` form is accepted as the alternative.
//
// Tabs with no page here are reported rather than skipped: a tab that reaches the docs with nothing
// naming it is the same failure seen from the other end.
const PAGES = {
  members: 'admin/members.md',
  spaces: 'admin/spaces.md',
  branding: 'admin/branding.md',
  auth: 'admin/sign-in-methods.md',
  api: 'admin/api-keys.md',
  webhooks: 'admin/webhooks.md',
  audit: 'admin/audit-log.md',
  analytics: 'admin/analytics.md',
  roles: 'admin/roles.md',
  embeds: 'admin/embeds.md',
  moderation: 'admin/moderation.md',
  billing: 'admin/billing.md',
  orphans: 'admin/orphaned-drafts.md',
  scim: 'admin/scim-provisioning.md',
  domains: 'admin/custom-domains.md',
  // The publishing guide is named after the feature, not the tab; it still has to name the tab.
  public: 'publishing/public-spaces.md',
}

if (!existsSync(TABLE)) {
  console.error(`check-admin-tab-names: ${TABLE} is missing — run \`pnpm pull:generated\` (it carries the product's tab labels).`)
  process.exit(1)
}
const { tabs } = JSON.parse(readFileSync(TABLE, 'utf8'))
const ids = Object.keys(tabs)
if (ids.length === 0) {
  console.error('check-admin-tab-names: the pulled table has no tabs — refusing a vacuously green run')
  process.exit(1)
}

const localePath = (locale, rel) => join(root, 'src/content/docs', locale === ROOT_LOCALE ? '' : locale, rel)
const titleOf = (text) => (/^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? '').match(/^title:\s*(.+)$/m)?.[1]?.trim()

const problems = []
let checked = 0

for (const locale of [ROOT_LOCALE, ...TRANSLATIONS]) {
  for (const id of ids) {
    const label = tabs[id]?.[locale]
    if (!label) {
      problems.push(`the product has no ${locale} label for the "${id}" tab — regenerate admin-tabs.json`)
      continue
    }
    const page = PAGES[id]
    if (!page) {
      problems.push(`the product has a "${id}" tab (${label}) and no page here documents it — add it to PAGES with its page`)
      continue
    }
    const file = localePath(locale, page)
    if (!existsSync(file)) {
      // ⚠️ #731: this skip used to apply to EVERY locale, and that made the check silent about
      // the one case it exists for. A page missing from a TRANSLATION is the translation's problem
      // and is reported by check-translation-coverage — naming it here too would be two files
      // reporting one fact. A page missing from the ROOT locale is a tab with no documentation at
      // all, and skipping it meant a shipped surface (the custom-domains tab) sat undocumented while
      // this check, the coverage check and the source repo's ledger were all green.
      if (locale !== ROOT_LOCALE) continue
      problems.push(`${locale}/${page}: the "${id}" tab (${label}) has no page at all — write it, or drop the row and record why`)
      continue
    }
    checked++
    const text = readFileSync(file, 'utf8')
    const introduced = [`Admin → ${label}`, `管理 → ${label}`].some((form) => text.includes(form))
    if (titleOf(text) !== label && !introduced) {
      problems.push(
        `${locale}/${page}: the product calls this tab "${label}" — make it the page title, or introduce it as ` +
        `"${locale === ROOT_LOCALE ? 'Admin' : '管理'} → ${label}" (the title is "${titleOf(text)}")`,
      )
    }
  }
}

// A page listed here whose tab no longer exists is a stale claim, the same way a stale ledger row is.
for (const id of Object.keys(PAGES)) {
  if (!ids.includes(id)) problems.push(`PAGES names a "${id}" tab the product no longer has — remove the row`)
}

if (problems.length > 0) {
  console.error('check-admin-tab-names FAILED:')
  for (const p of problems) console.error(`  - ${p}`)
  console.error('\nThe product is the authority (#731). Change the page, or change the product and regenerate.')
  process.exit(1)
}
console.log(`check-admin-tab-names OK — ${ids.length} tabs × ${1 + TRANSLATIONS.length} locale(s), ${checked} page checks`)
